S.lines.forEach((l) => l.items.forEach((s) => { if (s.demo) must(PROTOS.includes(s.demo.replace(/^#demo-/, "")), "the panel " + s.demo + " that the service \"" + s.id + "\" links to"); }));
// One late stylesheet instead of one per prototype: several stylesheet links added late measured much slower.
// Comments stay in the source files (no prototype stylesheet has a comment mark inside a string or an address).
const bare = (css) => css.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\n\s*\n/g, "\n").trim();
const demosCss = "/* GENERATED by tools/build-services.mjs from assets/demos/<name>.css, in the order of the panels in index.html.\n" +
  "   Do not edit this file: edit the prototype's own stylesheet and run the build. assets/lab.js appends it late. */\n" +
  PROTOS.map((n) => "/* " + n + " */\n" + bare(read("assets/demos/" + n + ".css"))).join("\n") + "\n";
writeFileSync(p("assets/demos.css"), demosCss);

/* ---------- 1. generated regions of the home page ---------- */
// the corridor map (assets/nwa-map.js keeps markup it finds, so the static copy and the script cannot drift)
put("nwa", corridorMap());
function corridorMap() {
  let out = "";
  const el = () => ({ classList: { add() {}, remove() {}, contains: () => false }, addEventListener() {}, querySelector: () => null, querySelectorAll: () => [], getAttribute: () => null });
  const host = el();
  Object.defineProperty(host, "innerHTML", { set(v) { out = v; throw new Error("captured"); }, get: () => out });
  try { vm.runInNewContext(read("assets/nwa-map.js"), { document: { getElementById: () => host, documentElement: el(), addEventListener() {} }, matchMedia: () => ({ matches: true }) }); }
  catch (e) { if (e.message !== "captured") throw e; }
  return must(out, "the corridor map markup in assets/nwa-map.js");
}
