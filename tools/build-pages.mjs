//   services/ and about/ links point at the sibling folder, or at "./" (marked as the current page) for the page itself;
//   #section links point at the home page; asset paths climb one level; hooks that only the home page's scripts use are dropped.
function rebase(s, page) {
  return s
    .replace(/href="(services|about)\/(#[^"]*)?"/g, (m, pg, hash) => (pg === page ? 'href="' + (hash || "./") + '"' + (hash ? "" : ' aria-current="page"') : 'href="../' + pg + "/" + (hash || "") + '"'))
    .replace(/href="#(?!i-|top"|main"|site-menu")([^"]*)"/g, 'href="../#$1"')
    .replace(/(src|href)="assets\//g, '$1="../assets/')
    .replace(/\sdata-go="[^"]*"/g, "").replace(/\sdata-ask="[^"]*"/g, "").replace(/\sdata-open-interest/g, "")
    .replace(/\sdata-reveal(="[^"]*")?/g, "").replace(/\sstyle="--i:\d+"/g, "");
}

